"""Generate grid configs (immutable once run). Two stages so nothing is ever edited:

    PYTHONPATH=src python scripts/make_grid_configs.py --grid pilot_v1 --stage tune
    PYTHONPATH=src python scripts/make_grid_configs.py --grid pilot_v1 --stage outer   # after select

Pre-registered tuning rule (docs/REALITY_CHECK.md P-01): epochs fixed (cosine schedule
to 0 over the full run); only lr is tuned, on inner fold 0 of outer fold 0 of the
RANDOM regime; winner = highest final-epoch inner-val pooled burned IoU, ties ->
smaller lr. The winner is frozen for both regimes and the as-published arm.
"""
import argparse
import json
import sys
from pathlib import Path

import pandas as pd
import yaml

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from burnscars.manifest import load_manifest  # noqa: E402
from burnscars.paths import outputs_dir  # noqa: E402

GRIDS = {
    "pilot_v1": {
        "model": "unet", "seed": 0, "epochs": 60, "batch_size": 8, "weight_decay": 0.05,
        "lrs": [3e-4, 1e-3, 3e-3], "tune_split": "splits/v1/random_cv5_ibm_trainval.json",
        "outer": [("random", "splits/v1/random_cv5_ibm_trainval.json", range(5)),
                  ("grouped", "splits/v1/grouped_cv5_ibm_trainval.json", range(5)),
                  ("published", "splits/v1/official.json", range(1))],
    },
}


def write(path: Path, cfg: dict):
    if path.exists() and yaml.safe_load(path.read_text()) != cfg:
        raise SystemExit(f"refusing to change existing config {path} (configs are immutable)")
    path.write_text("# generated by scripts/make_grid_configs.py — do not edit\n" + yaml.safe_dump(cfg, sort_keys=True))


def tune_name(lr):
    return f"tune_lr{lr:g}"


def select(grid: str, g: dict) -> dict:
    rows = []
    for lr in g["lrs"]:
        m = load_manifest(outputs_dir() / "grid" / grid / tune_name(lr), require_clean=True)
        h = pd.read_csv(outputs_dir() / "grid" / grid / tune_name(lr) / "history.csv")
        rows.append({"lr": lr, "final_inner_val_iou_burned": float(h["val_dataset_iou_burned"].iloc[-1]),
                     "manifest_sha": m["git_sha"]})
    best = sorted(rows, key=lambda r: (-r["final_inner_val_iou_burned"], r["lr"]))[0]
    return {"rows": rows, "selected_lr": best["lr"]}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--grid", required=True, choices=sorted(GRIDS))
    ap.add_argument("--stage", required=True, choices=["tune", "outer"])
    a = ap.parse_args()
    g = GRIDS[a.grid]
    d = REPO / "configs" / "grid" / a.grid
    d.mkdir(parents=True, exist_ok=True)
    base = {"model": g["model"], "seed": g["seed"], "epochs": g["epochs"], "batch_size": g["batch_size"],
            "weight_decay": g["weight_decay"], "cache_ram": True, "ckpt_every": 200}
    if a.stage == "tune":
        for lr in g["lrs"]:
            n = tune_name(lr)
            write(d / f"{n}.yaml", {**base, "lr": lr, "split_file": g["tune_split"], "fold": 0,
                                    "inner_fold": 0, "role": "inner_val", "out": f"grid/{a.grid}/{n}"})
        print(f"wrote {len(g['lrs'])} tuning configs to {d}")
        return
    sel = select(a.grid, g)
    (d / "selection.json").write_text(json.dumps(sel, indent=1) + "\n")
    n_out = 0
    for regime, split, folds in g["outer"]:
        for f in folds:
            n = f"{g['model']}_{regime}_f{f}_s{g['seed']}"
            write(d / f"{n}.yaml", {**base, "lr": sel["selected_lr"], "split_file": split, "fold": f,
                                    "role": "outer_test", "out": f"grid/{a.grid}/{n}"})
            n_out += 1
    print(f"selected lr={sel['selected_lr']}; wrote {n_out} outer configs to {d}")


if __name__ == "__main__":
    main()
